        "SYSTEM" to "System",
        "EN" to "English",
        "TR" to "Türkçe",
        "DE" to "Deutsch",
        "RU" to "Русский",
        "ZH" to "简体中文"
    )

    fun resolveStrings(langCode: String): AppStrings {
        val effective = if (langCode == "SYSTEM") {
            val sys = Locale.getDefault().language.uppercase(Locale.ROOT)
            if (sys in listOf("TR", "EN", "DE", "RU", "ZH")) sys else "EN"
        } else {
            langCode
        }
        return when (effective) {
            "TR" -> TrStrings
            "DE" -> DeStrings
            "RU" -> RuStrings
            "ZH" -> ZhStrings
            else -> EnStrings
        }
    }


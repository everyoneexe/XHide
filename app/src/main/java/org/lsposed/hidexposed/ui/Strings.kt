    )

    fun resolveStrings(langCode: String): AppStrings {
        val effective = if (langCode == "SYSTEM") {
            val sys = Locale.getDefault().language.uppercase(Locale.ROOT)
            if (sys in listOf("TR", "EN", "DE", "RU", "ZH")) sys else "TR"
        } else {
            langCode
        }
        return when (effective) {
            "TR" -> TrStrings
            "DE" -> DeStrings
            "RU" -> RuStrings
            "ZH" -> ZhStrings
            else -> EnStrings
        }
    }

